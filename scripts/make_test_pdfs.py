"""Generate SYNTHETIC test PDFs so the pipeline can be smoke-tested offline.

Why this exists
---------------
You need *some* PDFs to prove the pipeline runs before you have chosen your
real open-access papers. Downloading papers automatically is not acceptable
(licensing), so this script writes three small, entirely fabricated documents
into `data/test_fixtures/`.

READ THIS CAREFULLY
-------------------
These documents are **fiction**. Every number, cohort, biomarker and finding in
them was invented by this script to exercise the code. They are not research,
they must never be cited, and they must never appear in `data/sample_papers/`
alongside real papers. Each page carries a visible SYNTHETIC banner so a
screenshot can never be mistaken for a real study.

Their one legitimate use: because this script *places* each fact on a known
page, the accompanying `evaluation/fixture_questions.csv` has genuinely
verifiable ground truth, which lets you see real Recall@K and MRR numbers for
the retrieval code itself before your real corpus is ready.

Run with:
    python scripts/make_test_pdfs.py
"""

